CREATE OR REPLACE VIEW v_high_protein_foods AS
SELECT food_name, food_category, calories_per_100g,
       protein_g, carbs_g, fat_g, is_vegetarian, is_vegan
FROM food_master
WHERE protein_g >= 20
ORDER BY protein_g DESC;

CREATE OR REPLACE VIEW v_low_calorie_foods AS
SELECT food_name, food_category, calories_per_100g,
       protein_g, carbs_g, fat_g, fiber_g
FROM food_master
WHERE calories_per_100g < 50
ORDER BY calories_per_100g ASC;

CREATE OR REPLACE VIEW v_vegan_foods AS
SELECT food_name, food_category, calories_per_100g,
       protein_g, carbs_g, fat_g, fiber_g
FROM food_master
WHERE is_vegan = 1
ORDER BY food_category, food_name;

CREATE OR REPLACE VIEW v_indian_foods AS
SELECT food_name, food_category, calories_per_100g,
       protein_g, carbs_g, fat_g, is_vegetarian
FROM food_master
WHERE food_category IN ('Indian_Staple','Indian_Curry','Indian_Snack','Indian_Sweet')
ORDER BY food_category, food_name;

